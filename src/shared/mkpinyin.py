'''Generate pinyin.js: a compact toneless character-to-pinyin table for sound matching.
Characters: GB2312 level 1 (3755 most common) plus every Han character in our vocabulary files.
Source of readings: pypinyin 0.53.0 (MIT), used only here at build time; nothing of it ships except the table.'''
import sys,os,json,re
sys.path.insert(0,os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','pyp','x'))
from pypinyin import pinyin,Style
chars=set()
for b1 in range(0xB0,0xD8):
    for b2 in range(0xA1,0xFF):
        try:chars.add(bytes([b1,b2]).decode('gb2312'))
        except UnicodeDecodeError:pass
for f in ['steps.json','say.js','faq.json','cells.json','voice.js','cab.js','view.js','../stork/storklinta.html','../billy/billy.html','../billy-oxberg/billy-oxberg.html']:
    chars|=set(re.findall(r'[一-鿿]',open(f,encoding='utf8').read()))
by,by2={},{}
for c in sorted(chars):
    r=[x.replace('ü','v') for x in pinyin(c,style=Style.NORMAL,heteronym=True)[0] if re.fullmatch(r'[a-zü]+',x)]
    r=list(dict.fromkeys(r))[:2]
    if r:by.setdefault(r[0],[]).append(c)
    if len(r)>1:by2.setdefault(r[1],[]).append(c)
g=lambda d:'|'.join(k+':'+''.join(v) for k,v in sorted(d.items()))
js='/* toneless pinyin for %d characters (GB2312 level 1 + our vocabulary), generated by mkpinyin.py from pypinyin 0.53.0 (MIT): PYT holds each character\'s main reading, PYT2 a second reading */\nconst PYT="%s",PYT2="%s";'%(len(chars),g(by),g(by2))
open('pinyin.js','w',encoding='utf8').write(js)
print(len(chars),'chars',len(by),'syllables',len(js.encode('utf8')),'bytes')
